static const glyph_t *find_glyph(char c)
{
	if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
	for (unsigned i = 0; i < sizeof(font) / sizeof(font[0]); i++)
		if (font[i].c == c) return &font[i];
	return 0;                                   /* space and unknown characters */
}

void hud_box(u32 *fb, int stride, int x, int y, int w, int h)
{
	/* Write only, never read: the frame buffer is non-cacheable, reads cost
	   ~0.2 us per pixel there (darkening by read-modify-write would take ~10 ms) */
	for (int j = y; j < y + h; j++) {
		u32 *row = fb + (long)j * stride;
		for (int i = x; i < x + w; i++)
			row[i] = 0x00101018;                    /* dark blue-grey */
	}
}

int hud_text(u32 *fb, int stride, int x, int y, int scale, u32 color, const char *s)
{
	int x0 = x;
	for (; *s; s++) {
		const glyph_t *g = find_glyph(*s);
		if (g) {
			for (int r = 0; r < 7; r++)
				for (int c = 0; c < 5; c++)
					if (g->rows[r][c] == '1')
						for (int dy = 0; dy < scale; dy++) {
							u32 *p = fb + (long)(y + r * scale + dy) * stride + x + c * scale;
							for (int dx = 0; dx < scale; dx++) p[dx] = color;
						}
		}
		x += 6 * scale;
	}
	return x - x0;
}

char *fmt_str(char *p, const char *s) { while (*s) *p++ = *s++; *p = 0; return p; }

char *fmt_uint(char *p, unsigned long v)
{
	char t[24]; int n = 0;
	do { t[n++] = (char)('0' + v % 10); v /= 10; } while (v);
	while (n) *p++ = t[--n];
	*p = 0;
	return p;
}

char *fmt_fix1(char *p, unsigned long v_x10)
{
	p = fmt_uint(p, v_x10 / 10);
	*p++ = '.';
	*p++ = (char)('0' + v_x10 % 10);
	*p = 0;
	return p;
}
